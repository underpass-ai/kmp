//! The table every release publishes and `kmp-mcp setup` installs.
//!
//! `distribution/lexical-bridge/kmp-lexical-bridge.kmpb` is copied into the
//! release candidate byte for byte, so this is the place to prove that the
//! bytes a release will ship are ones this kernel reads, that the checksum
//! beside them is theirs, and that the pairs the documentation promises
//! actually bridge.

use std::path::PathBuf;

use kmp_proto_mapping::v1beta1::LexicalBridge;
use sha2::{Digest, Sha256};

fn shipped() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("../../distribution/lexical-bridge")
        .join("kmp-lexical-bridge.kmpb")
}

fn table() -> LexicalBridge {
    let bytes = std::fs::read(shipped()).expect("the shipped table is committed");
    LexicalBridge::from_owned_bytes(bytes).expect("the shipped table is one this kernel reads")
}

#[test]
fn the_shipped_table_is_one_this_kernel_reads() {
    let bridge = table();

    assert!(!bridge.is_silent());
    assert!(bridge.len() > 100_000, "{} words", bridge.len());
    assert_eq!(
        bridge.provenance(),
        "sentence-transformers/static-similarity-mrl-multilingual-v1"
    );
}

/// `setup` compares the digest a release publishes against the bytes it
/// downloads; the committed checksum is the one the release will publish.
#[test]
fn the_committed_checksum_is_the_tables_own() {
    let path = shipped();
    let bytes = std::fs::read(&path).expect("the shipped table is committed");
    let recorded = std::fs::read_to_string(path.with_extension("kmpb.sha256"))
        .expect("the checksum sits beside the table");

    let actual = format!("{:x}", Sha256::digest(&bytes));
    assert_eq!(recorded.split_whitespace().next(), Some(actual.as_str()));
    assert!(recorded.trim_end().ends_with("kmp-lexical-bridge.kmpb"));
}

/// The pairs the README cites as what the table does.
#[test]
fn the_documented_pairs_bridge_at_the_kernels_bar() {
    let bridge = table();

    for (spanish, english) in [
        ("valvula", "valve"),
        ("noche", "night"),
        ("fabrica", "factory"),
        ("cliente", "customer"),
        ("reunion", "meeting"),
    ] {
        let similarity = bridge
            .similarity(spanish, english)
            .unwrap_or_else(|| panic!("{spanish} and {english} are both in the shipped table"));
        assert!(
            similarity >= 0.45,
            "{spanish}\u{2248}{english} scores {similarity:.2}, below the 0.45 bar"
        );
    }
    assert!(
        bridge.similarity("valvula", "night").unwrap_or(1.0) < 0.45,
        "unrelated words do not bridge"
    );
}

/// The stress cases `retrieval-baseline.sh` also scores with this table:
/// synthetic negatives whose answer is not stored, and cross-language
/// questions whose answer is (`tests/fixtures/lexical_bridge_stress/`,
/// generated by `scripts/performance/memory_bench/tools/gen_retrieval_bridge_cases.py`).
fn stress_cases() -> Vec<serde_json::Value> {
    let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("tests/fixtures/lexical_bridge_stress/cases.json");
    let collection: serde_json::Value = serde_json::from_str(
        &std::fs::read_to_string(path).expect("the stress cases are committed"),
    )
    .expect("the stress cases parse");
    collection["cases"]
        .as_array()
        .expect("a list of cases")
        .clone()
}

async fn call(
    server: &kmp_mcp::KernelMcpServer,
    name: &str,
    arguments: serde_json::Value,
) -> serde_json::Value {
    let request = serde_json::json!({
        "jsonrpc": "2.0", "id": 1, "method": "tools/call",
        "params": {"name": name, "arguments": arguments}
    })
    .to_string();
    let response = server
        .handle_json_line(&request)
        .await
        .expect("an MCP response");
    let response: serde_json::Value = serde_json::from_str(&response).expect("JSON");
    assert_ne!(response["result"]["isError"], true, "{response}");
    response["result"]["structuredContent"].clone()
}

/// One case on a fresh store that reads the shipped table from beside it,
/// as `kmp-mcp setup` leaves it for every user.
async fn ask_case(case: &serde_json::Value) -> serde_json::Value {
    let dir = tempfile::tempdir().expect("a scratch store");
    let beside = dir.path().join("lexical-bridge.kmpb");
    #[cfg(unix)]
    std::os::unix::fs::symlink(shipped(), &beside).expect("the table beside the store");
    #[cfg(not(unix))]
    std::fs::copy(shipped(), &beside).expect("the table beside the store");
    let server = kmp_mcp::KernelMcpServer::embedded(dir.path()).expect("an embedded store");
    let receipt = call(
        &server,
        "kmp_ingest",
        serde_json::json!({
            "about": case["about"],
            "idempotency_key": format!("stress:{}", case["id"].as_str().unwrap_or_default()),
            "memory": case["memory"],
        }),
    )
    .await;
    assert_eq!(receipt["accepted"], true, "{}: {receipt}", case["id"]);
    call(
        &server,
        "kmp_ask",
        serde_json::json!({
            "about": case["about"],
            "question": case["question"],
            "answer_policy": "evidence_or_unknown",
        }),
    )
    .await
}

/// `kmp_ask` never answers what is not stored, with the table every user
/// gets as with none: the table's neighbours inside one language
/// (`deadline≈final`, `prefix≈prefer`) never stand in for what a question
/// asked, and a question it translates is never `high` on the table's word.
/// Before the fix (integration/v1.0 at dee3d0ea), 43 of these 67 negatives
/// were answered, 13 of them `high`.
#[tokio::test]
async fn the_shipped_table_never_answers_a_stress_negative() {
    if std::env::var_os("KMP_LEXICAL_BRIDGE").is_some() {
        panic!("unset KMP_LEXICAL_BRIDGE: this test reads the shipped table beside each store");
    }
    let mut answered = Vec::new();
    let mut translated = 0;
    for case in stress_cases() {
        let answer = ask_case(&case).await;
        let status = answer["answer_status"].as_str().unwrap_or_default();
        let confidence = answer["proof"]["confidence"].as_str().unwrap_or_default();
        let judged = case["judged"].as_array().expect("judged refs");
        let across = case["kind"] == "crosslang_gold_out";
        if !judged.is_empty() {
            translated += usize::from(status == "answered");
        } else if status != "unknown" && (!across || confidence == "high") {
            answered.push(format!("{} ({status}, {confidence})", case["id"]));
        }
    }
    // A negative in one language is never answered. One across a language
    // (`crosslang_gold_out`) stands on the table's translation, which can be
    // wrong; it may answer at `medium`, never `high`.
    assert!(answered.is_empty(), "negatives answered: {answered:#?}");
    // The table still crosses a language.
    assert!(translated > 0, "no cross-language question was answered");
}
